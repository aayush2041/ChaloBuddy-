export function searchDestinations(query) {
  if (!query || typeof query !== 'string' || !query.trim()) {
    return DESTINATIONS_DATABASE.slice(0, 6);
  }

  const clean = query.trim().toLowerCase();

  return DESTINATIONS_DATABASE.filter((dest) => {
    return (
      dest.city.toLowerCase().includes(clean) ||
      dest.state.toLowerCase().includes(clean) ||
      dest.fullName.toLowerCase().includes(clean) ||
      dest.type.toLowerCase().includes(clean) ||
      dest.id.toLowerCase().includes(clean) ||
      dest.popularSpots.some((spot) => spot.toLowerCase().includes(clean))
    );
  }).sort((a, b) => {
    // 1. Exact match on city name
    if (a.city.toLowerCase() === clean && b.city.toLowerCase() !== clean) return -1;
    if (b.city.toLowerCase() === clean && a.city.toLowerCase() !== clean) return 1;

    // 2. City starts with query
    const aStartsWith = a.city.toLowerCase().startsWith(clean);
    const bStartsWith = b.city.toLowerCase().startsWith(clean);
    if (aStartsWith && !bStartsWith) return -1;
    if (!aStartsWith && bStartsWith) return 1;

    // 3. Shorter city name first (e.g. 'Delhi' before 'Delhi NCR')
    if (aStartsWith && bStartsWith) {
      if (a.city.length !== b.city.length) return a.city.length - b.city.length;
    }

    // 4. State starts with query
    const aStateStarts = a.state.toLowerCase().startsWith(clean);
    const bStateStarts = b.state.toLowerCase().startsWith(clean);
    if (aStateStarts && !bStateStarts) return -1;
    if (!aStateStarts && bStateStarts) return 1;

    return a.city.localeCompare(b.city);
  });
}
